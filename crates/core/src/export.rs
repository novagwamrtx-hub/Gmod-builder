//! Text outputs: server files and collection descriptions.

use std::collections::HashMap;

use crate::gma::Archive;
use crate::model::{Addon, AddonStatus, Kind};

/// Lua file that makes joining clients download the collection's content.
/// Goes in `garrysmod/lua/autorun/server/`.
///
/// For addons whose archive is in `archives`, the file is trimmed to what
/// clients need: script-only addons are left out (scripts reach clients
/// through the server), and a map is only sent while the server is on it.
/// Addons without an archive are always sent.
pub fn workshop_lua(addons: &[Addon], archives: &HashMap<u64, Archive>) -> String {
    let mut out = String::from(
        "-- Generated by GMod Collection Builder\n-- Place in garrysmod/lua/autorun/server/workshop.lua\n\n",
    );
    let mut maps = Vec::new();
    let mut skipped = Vec::new();
    for addon in addons.iter().filter(|a| a.status == AddonStatus::Ok) {
        let title = one_line(&addon.display_title());
        let archive = archives.get(&addon.id);
        let map_names = archive.map(Archive::maps).unwrap_or_default();
        if archive.is_some_and(Archive::is_lua_only) {
            skipped.push(title);
        } else if addon.kind() == Kind::Map && !map_names.is_empty() {
            maps.push((addon.id, title, map_names));
        } else {
            out.push_str(&format!("resource.AddWorkshop(\"{}\") -- {}\n", addon.id, title));
        }
    }
    if !maps.is_empty() {
        out.push_str("\n-- Maps are only sent while the server is running them.\nlocal maps = {\n");
        for (id, title, names) in &maps {
            for name in names {
                out.push_str(&format!("    [\"{name}\"] = \"{id}\", -- {title}\n"));
            }
        }
        out.push_str("}\nlocal map = maps[game.GetMap()]\nif map then resource.AddWorkshop(map) end\n");
    }
    if !skipped.is_empty() {
        out.push_str("\n-- Left out because they contain only scripts, which clients get from the server:\n");
        for title in skipped {
            out.push_str(&format!("--   {title}\n"));
        }
    }
    out
}

/// Launch option that makes a dedicated server download the collection.
pub fn launch_options(collection_id: u64) -> String {
    format!("+host_workshop_collection {collection_id}")
}

pub fn id_list(ids: &[u64]) -> String {
    ids.iter().map(u64::to_string).collect::<Vec<_>>().join("\n")
}

/// The collection as a list grouped by type, in Steam's BBCode, for the
/// description of the collection's Workshop page.
pub fn description_bbcode(addons: &[Addon]) -> String {
    let mut out = String::new();
    for (kind, group) in by_kind(addons) {
        out.push_str(&format!("[h2]{} ({})[/h2]\n[list]\n", kind.label(), group.len()));
        for addon in group {
            let title = one_line(&addon.display_title()).replace(['[', ']'], "");
            out.push_str(&format!("[*] [url={}]{}[/url]\n", addon.url(), title));
        }
        out.push_str("[/list]\n\n");
    }
    out.trim_end().to_string()
}

/// The same list in Markdown, as Discord renders it.
pub fn description_markdown(addons: &[Addon]) -> String {
    let mut out = String::new();
    for (kind, group) in by_kind(addons) {
        out.push_str(&format!("**{} ({})**\n", kind.label(), group.len()));
        for addon in group {
            let title = one_line(&addon.display_title()).replace(['[', ']'], "");
            // Angle brackets stop Discord from embedding a preview per link.
            out.push_str(&format!("- [{}](<{}>)\n", title, addon.url()));
        }
        out.push('\n');
    }
    out.trim_end().to_string()
}

/// Available addons grouped by kind, groups in [`Kind::ALL`] order.
pub fn by_kind(addons: &[Addon]) -> Vec<(Kind, Vec<&Addon>)> {
    Kind::ALL
        .into_iter()
        .map(|kind| {
            let group: Vec<&Addon> =
                addons.iter().filter(|a| a.status == AddonStatus::Ok && a.kind() == kind).collect();
            (kind, group)
        })
        .filter(|(_, group)| !group.is_empty())
        .collect()
}

fn one_line(text: &str) -> String {
    text.chars().filter(|c| !c.is_control()).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn addon(id: u64, title: &str, tag: &str) -> Addon {
        Addon { title: title.into(), tags: vec![tag.into()], ..Addon::unavailable(id, AddonStatus::Ok) }
    }

    #[test]
    fn lua_skips_unavailable_and_keeps_comments_on_one_line() {
        let ok = addon(1, "Wire\nmod", "tool");
        let gone = Addon::unavailable(2, AddonStatus::Removed);
        let lua = workshop_lua(&[ok, gone], &HashMap::new());
        assert!(lua.ends_with("resource.AddWorkshop(\"1\") -- Wiremod\n"));
        assert!(!lua.contains("\"2\""));
    }

    #[test]
    fn lua_uses_archives_to_send_only_what_clients_need() {
        let addons = [addon(1, "Admin", "tool"), addon(2, "Big City", "map"), addon(3, "Guns", "weapon")];
        let archive = |files: &[&str]| Archive {
            title: String::new(),
            files: files.iter().map(|f| f.to_string()).collect(),
        };
        let archives = HashMap::from([
            (1, archive(&["lua/autorun/admin.lua"])),
            (2, archive(&["maps/gm_bigcity.bsp", "maps/gm_bigcity_night.bsp", "materials/a.vmt"])),
        ]);
        let lua = workshop_lua(&addons, &archives);
        assert!(!lua.contains("AddWorkshop(\"1\")"));
        assert!(lua.contains("--   Admin\n"));
        assert!(!lua.contains("AddWorkshop(\"2\")"));
        assert!(lua.contains("    [\"gm_bigcity_night\"] = \"2\", -- Big City\n"));
        assert!(lua.contains("if map then resource.AddWorkshop(map) end"));
        // No archive for the guns, so they are sent as before.
        assert!(lua.contains("resource.AddWorkshop(\"3\") -- Guns\n"));
    }

    #[test]
    fn plain_outputs() {
        assert_eq!(launch_options(42), "+host_workshop_collection 42");
        assert_eq!(id_list(&[1, 2, 3]), "1\n2\n3");
    }

    #[test]
    fn descriptions_group_by_kind() {
        let addons = [
            addon(1, "[TFA] Guns", "Weapon"),
            addon(2, "gm_flatgrass", "map"),
            Addon::unavailable(3, AddonStatus::Removed),
        ];
        assert_eq!(
            description_bbcode(&addons),
            "[h2]Maps (1)[/h2]\n[list]\n[*] [url=https://steamcommunity.com/sharedfiles/filedetails/?id=2]gm_flatgrass[/url]\n[/list]\n\n\
             [h2]Weapons (1)[/h2]\n[list]\n[*] [url=https://steamcommunity.com/sharedfiles/filedetails/?id=1]TFA Guns[/url]\n[/list]"
        );
        assert_eq!(
            description_markdown(&addons),
            "**Maps (1)**\n- [gm_flatgrass](<https://steamcommunity.com/sharedfiles/filedetails/?id=2>)\n\n\
             **Weapons (1)**\n- [TFA Guns](<https://steamcommunity.com/sharedfiles/filedetails/?id=1>)"
        );
    }
}
